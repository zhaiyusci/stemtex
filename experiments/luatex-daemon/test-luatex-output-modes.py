"""Check that per-shipout DVI flushing is opt-in and does not change PDF output.

Run with the patched engine and a plain format generated by that engine version.
TEXMFCNF/TEXMFROOT and other runtime settings are inherited unchanged.
"""
import argparse
import hashlib
import json
import os
from pathlib import Path
import queue
import runpy
import shutil
import subprocess
import tempfile
import threading
import time

ROOT = Path(__file__).resolve().parents[2]
DVI_PROBE = runpy.run_path(str(Path(__file__).with_name("live-dvi-probe.py")))
TEX = r"""\font\testfont=cmr10\testfont
@PDF_SETUP@
\def\signal#1{\directlua{io.stdout:write(string.char(10).."#1"..string.char(10)); io.stdout:flush()}}
\signal{MODE_READY}
\read16 to\startline
\shipout\vbox{\hbox{StemTeX output mode check: ABC 0123456789}}
\signal{MODE_SHIPPED}
\read16 to\stopline
\bye
"""


def run_mode(options, run_dir, output_format, enabled):
    name = f"{output_format}-{'on' if enabled else 'off'}"
    work = run_dir / name
    work.mkdir()
    # Dates are fixed by SOURCE_DATE_EPOCH below. Suppress optional PDF info,
    # including file paths/IDs, so directory names cannot affect byte comparison.
    pdf_setup = r"\pdfvariable suppressoptionalinfo=1023\relax" if output_format == "pdf" else ""
    (work / "worker.tex").write_text(TEX.replace("@PDF_SETUP@", pdf_setup), encoding="ascii")
    env = os.environ.copy()
    env["SOURCE_DATE_EPOCH"] = "946684800"
    executable = shutil.which(options.engine)
    if not executable:
        raise RuntimeError(f"Cannot find engine: {options.engine}")
    command = [executable, f"--fmt={options.plain_format}", "--progname=luatex",
               f"--output-format={output_format}", "--jobname=worker",
               "--interaction=errorstopmode", "--halt-on-error", "--no-shell-escape"]
    if enabled:
        command.append("--flush-output-on-shipout")
    command.append("worker.tex")
    process = subprocess.Popen(command, cwd=work, env=env, stdin=subprocess.PIPE,
                               stdout=subprocess.PIPE, stderr=subprocess.STDOUT,
                               text=True, encoding="utf-8", errors="replace")
    lines, transcript = queue.Queue(), []

    def collect():
        for line in process.stdout:
            transcript.append(line)
            lines.put(line.strip())
        lines.put(None)

    reader = threading.Thread(target=collect, daemon=True)
    reader.start()

    def until(marker):
        deadline = time.monotonic() + 45
        while True:
            try:
                line = lines.get(timeout=max(0.01, deadline - time.monotonic()))
            except queue.Empty as exc:
                raise TimeoutError(f"Waiting for {marker}") from exc
            if line is None:
                raise RuntimeError(f"Engine ended before {marker}\n{''.join(transcript[-15:])}")
            if line == marker:
                return
            if time.monotonic() >= deadline:
                raise TimeoutError(f"Waiting for {marker}")

    def send(value):
        process.stdin.write(value + "\n")
        process.stdin.flush()

    report = {"mode": name, "command": command, "pid": process.pid,
              "work_directory": str(work), "source_date_epoch": env["SOURCE_DATE_EPOCH"]}
    artifact = work / f"worker.{output_format}"
    try:
        until("MODE_READY")
        send("start")
        until("MODE_SHIPPED")
        assert process.poll() is None, "Engine must still be alive after shipout"
        live = artifact.read_bytes() if artifact.exists() else b""
        (work / f"live.{output_format}").write_bytes(live)
        report["live_bytes"] = len(live)
        if output_format == "dvi":
            pages, has_post = DVI_PROBE["parse_dvi"](live)
            report["live_complete_pages"] = len(pages)
            assert not has_post, "Live DVI must not contain a postamble"
            if enabled:
                assert len(pages) == 1 and pages[0]["end"] == len(live), "Enabled flush did not expose exactly one complete page"
            else:
                assert not live, f"Default-off small DVI unexpectedly flushed {len(live)} bytes"
        send("stop")
        report["exit_code"] = process.wait(timeout=30)
        assert report["exit_code"] == 0, "Engine failed during normal shutdown"
        final = artifact.read_bytes()
        report["final_bytes"] = len(final)
        report["sha256"] = hashlib.sha256(final).hexdigest()
        if output_format == "dvi":
            report["structure"] = DVI_PROBE["verify_final_dvi"](final, 1)
        else:
            assert final.startswith(b"%PDF-") and b"%%EOF" in final[-100:], "PDF was not finalized"
            pdfinfo = shutil.which("pdfinfo")
            if pdfinfo:
                checked = subprocess.run([pdfinfo, str(artifact)], capture_output=True,
                                         text=True, encoding="utf-8", errors="replace", timeout=15)
                (work / "pdfinfo.log").write_text(checked.stdout + checked.stderr, encoding="utf-8")
                assert checked.returncode == 0, "pdfinfo rejected native PDF"
                assert any(line.split() == ["Pages:", "1"] for line in checked.stdout.splitlines()), "Native PDF is not one page"
                report["pdfinfo_pages"] = 1
    except Exception as exc:
        report["error"] = f"{type(exc).__name__}: {exc}"
    finally:
        if process.poll() is None:
            process.kill()
            process.wait(timeout=10)
        reader.join(timeout=5)
        (work / "console.log").write_text("".join(transcript), encoding="utf-8")
        process.stdin.close()
        process.stdout.close()
    (work / "result.json").write_text(json.dumps(report, indent=2), encoding="utf-8")
    return report


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--engine", required=True, help="patched LuaTeX/LuaHBTeX executable")
    parser.add_argument("--plain-format", default="luatex", help="matching plain format name or absolute path")
    parser.add_argument("--output-directory", type=Path, default=ROOT / "build" / "luatex-output-modes")
    options = parser.parse_args()
    output_root = options.output_directory.resolve()
    output_root.mkdir(parents=True, exist_ok=True)
    run_dir = Path(tempfile.mkdtemp(prefix="run-", dir=output_root))
    report = {"run_directory": str(run_dir), "runs": []}
    for output_format in ("dvi", "pdf"):
        for enabled in (False, True):
            try:
                result = run_mode(options, run_dir, output_format, enabled)
            except Exception as exc:
                result = {"mode": f"{output_format}-{'on' if enabled else 'off'}",
                          "error": f"{type(exc).__name__}: {exc}"}
            report["runs"].append(result)
    failures = [run for run in report["runs"] if "error" in run]
    if not failures:
        for output_format in ("dvi", "pdf"):
            off = (run_dir / f"{output_format}-off" / f"worker.{output_format}").read_bytes()
            on = (run_dir / f"{output_format}-on" / f"worker.{output_format}").read_bytes()
            report[f"{output_format}_on_off_byte_identical"] = off == on
            if off != on:
                failures.append({"error": f"Final {output_format.upper()} differs with flush enabled"})
    report["passed"] = not failures
    if failures:
        report["errors"] = [failure["error"] for failure in failures]
    summary = json.dumps(report, indent=2)
    (run_dir / "results.json").write_text(summary, encoding="utf-8")
    (output_root / "results.json").write_text(summary, encoding="utf-8")
    print(summary)
    return 0 if report["passed"] else 1


if __name__ == "__main__":
    raise SystemExit(main())
